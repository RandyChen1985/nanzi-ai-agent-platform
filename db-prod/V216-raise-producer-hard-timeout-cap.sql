-- V216: 放宽 producer 硬超时看门狗的上限（60-3600 → 60-86400）（MySQL）
--
-- 背景：工具级超时已允许配置到 86400 秒（可超过版本级/全局级的默认值），但看门狗上限
-- 仍是 3600，于是「给慢工具配的长预算」永远跑不完——整轮会在 3600 秒被强制取消。
-- 上限与工具级/版本级超时对齐到 86400，语义才自洽。
--
-- 只改描述，不动 value：默认值仍是 600 秒，正常对话的兜底时长不受影响；调大上限只影响
-- 「producer 卡死时最晚多久被强杀」。
--
-- 0 表示关闭看门狗的语义保持不变。关闭虽然能解掉这个天花板，但会失去「会话最终一定被
-- 释放」的兜底，因此仍建议通过调大上限而不是关闭来解决长超时需求。
UPDATE `system_configs`
SET `description` = 'producer 硬超时看门狗（秒）：整轮对话的总时长兜底，超时会取消本轮并释放会话锁。默认 600，范围 60-86400，填 0 表示关闭。注意它约束的是整轮（含所有工具调用、模型调用以及工具级超时配置），因此任何比它大的工具超时都不会生效——工具还没到自己的超时，整轮就先被取消。'
WHERE `key` = 'agent_chat_producer_hard_timeout_seconds';
