-- V213: 数据集加「业务分组」（单值归属，仅用于列表页页签与筛选）。
--
-- 与 `tags`（JSON 多值、会进「已授权数据集目录」提示词）刻意分开：
--   group_name = 这个数据集归谁管（一个业务域，单值）→ 页面导航/筛选
--   tags       = 它有什么属性（可多个）              → AI 选库
-- 混用会出现「一个数据集挂在多个页签、各页签计数相加大于总数」，也没有「未分组」可看。
--
-- 可空、无默认值：存量行全部落成 NULL，前端按「未分组」展示与统计，
-- 不需要数据回填，也不影响任何既有查询。
--
-- 幂等：MySQL 8.0 没有 `ADD COLUMN IF NOT EXISTS`，而 `apply_sql.py` 没有版本记录表、
-- 整文件重放，只按语句粒度忽略错误码（1060 列已存在）。这里只有一条 ALTER，
-- 重复执行会被 1060 忽略，无副作用。

ALTER TABLE `meta_datasets`
  ADD COLUMN `group_name` VARCHAR(64) NULL
    COMMENT '业务分组：单值归属，服务列表页页签与筛选；不进 AI 提示词';
