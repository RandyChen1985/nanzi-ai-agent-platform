-- 原因：为 API 工具（sys_api_tools）增加业务分组字段
-- 需求背景：通过「API 工具注册表」登记的自定义接口，在智能体配置的「工具能力」步骤里会
--           全部落进「其他扩展工具」兜底组——因为分组是按工具名关键字硬编码猜测的，而该表
--           没有任何分组信息。工具一多（几十上百个）就无法按业务域查找、勾选与管理。
-- 变更范围：仅新增一个可空列，**不改动任何既有数据**（存量工具 group_name 为 NULL，分组
--           结果与改动前完全一致，仍走原有关键字回落逻辑）。
-- 创建人：Antigravity
-- 创建时间：2026-10-08

ALTER TABLE `sys_api_tools`
  ADD COLUMN `group_name` VARCHAR(64) NULL COMMENT '业务分组名（智能体配置里按它归组，NULL 表示未分组）' AFTER `is_active`;
