-- V220: 绑定表加 `binding_group_id`——记录「这条绑定属于哪一次多值配置」。（MySQL）
--
-- 背景：同一个 MCP / API 工具的参数可以有两种配法，落库后**完全同形**：
--
--   单值配法   每个参数各配一次，可能是不同的凭据、不同的规则
--   多值配法   一次保存，N 个参数共用同一份凭据（或同一条规则），各自只取不同字段
--
-- 两种配法写出来的都是「N 个 slot 各一条 sys_secret_bindings 行」，库里分辨不出来。
-- 由此带来三个实际问题：
--
--   1. 参数设置的「单值凭据」页按 slot 逐行渲染，看到 strategy='rule' 就显示
--      「按规则匹配」。多值配法写的也是 slot 级 rule 行，于是重开页面看起来像
--      「每个参数被单独配了一条规则」——用户配的是一条规则映射多个字段，
--      看到的却是 N 条独立规则。
--   2. 那一页每一行都有「改规则」。改其中一行只改这一个 slot，其余 N-1 个还是
--      旧规则，多值结构被悄悄拆散，而系统不知道原本是一组。
--   3. 注入时按 slot 逐个解析，同一条规则被重复执行 N 遍。其中「可见集合」
--      这一项只取决于当前用户，与槽位无关，却每个槽位都重查一次（还带权限与
--      场景过滤）——多值配法下这是最明显的浪费。已用单次调用级的
--      `visible_cache` 消掉（`resolver.resolve` 的入参，注入层每个入口传同一份，
--      作用域是一次工具调用，不跨调用，也不缓存明文）。
--      规则本身仍按 slot 各算一遍：不同槽位的 `value_path` 不同，且解析路径上
--      还有场景/域名/授权四道闸门要各自记录流水，合并反而会让「哪个槽位被谁
--      拦下」变得说不清。
--
-- 加这一列等于把「组」显式记下来，让展示和注入都不必再靠「几个 slot 的
-- rule_json 是否相同」去猜（那个推断在用户单独改过某个 slot 之后就不成立了）。
--
-- 取值语义：
--   NULL        单值配法（也是全部存量行的默认，无需回填）
--   uuid 字符串  多值配法：一次 bindings/batch 保存生成一个，这一批 N 条共享
--
-- 不加唯一约束：`uk_binding_slot` 已经保证了 (consumer, slot, bound_by) 唯一，
-- 同组内一行一个 slot，本来就撞不上。
--
-- 幂等：MySQL 8.0 没有 `ADD COLUMN IF NOT EXISTS`，靠 `apply_sql.py` 按语句粒度
-- 忽略 1060（列已存在）。单条 ALTER，重复执行只会命中一次 1060。

ALTER TABLE `sys_secret_bindings`
  ADD COLUMN `binding_group_id` VARCHAR(36) NULL
    COMMENT '多值配法的组标识（一次整表保存生成一个，该批各行共享）；单值配法为 NULL';

-- 注入侧要按组取同批内的其它 slot，给个普通索引（不唯一）。
-- 单独一条语句：上面那条在已执行过的库上会被整条忽略，索引塞进去就永远补不上。
CREATE INDEX `idx_binding_group` ON `sys_secret_bindings` (`binding_group_id`);
