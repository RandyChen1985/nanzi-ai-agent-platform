def test_pg_importer_splits_dollar_quoted_and_string_semicolons():
    module = load_apply_sql_module()

    statements = module.split_sql_statements(
        """
        CREATE TABLE demo (id integer);
        INSERT INTO demo VALUES (1, 'value;still-one-statement');
        DO $$
        BEGIN
            PERFORM 1;
        END
        $$;
        """
    )

    assert len(statements) == 3
    assert "value;still-one-statement" in statements[1]
    assert statements[2].startswith("DO $$")


