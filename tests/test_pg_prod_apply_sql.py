def test_pg_baseline_has_chinese_comments_for_every_baseline_column():
    baseline = (PG_PROD / "V0-baseline.sql").read_text(encoding="utf-8")

    column_definitions = re.findall(r'^\s+"[^"]+"\s+', baseline, flags=re.MULTILINE)
    column_comments = re.findall(r'^COMMENT ON COLUMN ', baseline, flags=re.MULTILINE)

    assert baseline.count("CREATE TABLE IF NOT EXISTS") == 44
    assert baseline.count("COMMENT ON TABLE") == 44
    assert len(column_comments) == len(column_definitions)
    assert re.search(r"[一-鿿]", baseline)


def test_pg_baseline_places_field_remarks_inside_create_tables():
    baseline = (PG_PROD / "V0-baseline.sql").read_text(encoding="utf-8")
    table_blocks = re.findall(
        r'CREATE TABLE IF NOT EXISTS "([^"]+)" \((.*?)\n\);',
        baseline,
        flags=re.DOTALL,
    )

    for table_name, body in table_blocks:
        lines = body.splitlines()
        for index, line in enumerate(lines):
            if re.match(r'^\s+"[^"]+"\s+', line):
                assert lines[index - 1].strip().startswith("--"), table_name


